import sys
from datetime import datetime
from pathlib import Path

SRC_DIR = Path(__file__).resolve().parents[2]
if str(SRC_DIR) not in sys.path:
    sys.path.insert(0, str(SRC_DIR))

import polars as pl
import streamlit as st

from city_pulse.dashboard.charts import (
    plot_heatmap,
    plot_timeseries,
    plot_weather_impact,
)
from city_pulse.dashboard.data import (
    DAY_NAMES,
    compute_heatmap_matrix,
    compute_kpis,
    compute_weather_impact,
    filter_by_day,
    load_latest_forecast,
)

st.set_page_config(
    page_title="Istanbul City Pulse | Traffic Forecast",
    page_icon="🚗",
    layout="wide",
    initial_sidebar_state="expanded",
)

try:
    df, filename = load_latest_forecast()
except FileNotFoundError:
    st.info(
        "⏳ **No Live Forecast Available Yet.**\n\n"
        "The forecast will be automatically generated by the Airflow scheduler "
        "and displayed here once ready."
    )
    st.stop()

with st.sidebar:
    st.image(
        "https://upload.wikimedia.org/wikipedia/commons/thumb/e/e0/Istanbul_Metropolitan_Municipality_logo.svg/512px-Istanbul_Metropolitan_Municipality_logo.svg.png",
        width=130,
    )
    st.markdown("### ⚙️ Filters & Settings")
    st.caption(f"📁 **Active Data File:**\n`{filename}`")

    day_options = ["All Week"] + list(DAY_NAMES.values())
    selected_day = st.selectbox("📅 Day Filter", day_options)

    traffic_threshold = float(
        st.slider(
            "🚨 Critical Traffic Threshold",
            min_value=30,
            max_value=80,
            value=50,
            step=5,
            help="Hours above this threshold are highlighted as critical in charts.",
        )
    )

    st.markdown("---")
    st.markdown(
        """
        **Architecture Stack:**
        - 📥 **Ingestion:** IBB Open Data & Open-Meteo
        - ⚙️ **Transformation:** dbt & DuckDB
        - 🤖 **MLOps:** LightGBM & MLflow
        - ⏱️ **Orchestration:** Apache Airflow
        """
    )

filtered_df = filter_by_day(df, selected_day)
kpis = compute_kpis(filtered_df, traffic_threshold)

st.title("🚗 Istanbul City Pulse — Live Traffic Forecast Dashboard")
st.markdown(
    "City traffic projection for the next **168 hours (7 days)** using Open-Meteo weather forecasts and a LightGBM machine learning model."
)

with st.container():
    c1, c2, c3, c4 = st.columns(4)
    with c1, st.container(border=True):
        st.metric(
            "🔥 Peak Hour",
            f"% {kpis.max_traffic_val:.1f}",
            delta=f"{kpis.max_traffic_time.strftime('%d %b %H:%M')}",
            delta_color="inverse",
        )
    with c2, st.container(border=True):
        st.metric(
            "📊 Expected Average Traffic",
            f"% {kpis.avg_traffic_val:.1f}",
        )
    with c3, st.container(border=True):
        st.metric(
            "🌧️ Rainy Hours Count",
            f"{kpis.rain_hours} Hours",
            delta=f"{kpis.total_rain_mm:.1f} mm rain",
        )
    with c4, st.container(border=True):
        st.metric(
            f"🚨 Critical Hours (≥ {traffic_threshold:.0f}%)",
            f"{kpis.critical_hours_count} Hours",
            delta="High Risk" if kpis.critical_hours_count > 12 else "Normal",
            delta_color="inverse" if kpis.critical_hours_count > 12 else "normal",
        )

st.write("")

tab_trend, tab_heatmap, tab_weather, tab_data = st.tabs(
    [
        "📈 168-Hour Traffic Trend",
        "🗓️ Day & Hour Heatmap",
        "🌧️ Weather Impact & Peak Hours",
        "🔍 Raw Data & Export",
    ]
)

with tab_trend:
    st.markdown("#### 7-Day Continuous Traffic and Precipitation Projection")
    st.caption("Use the range slider below to zoom in on specific days and hours.")
    fig_ts = plot_timeseries(filtered_df.to_pandas(), traffic_threshold)
    st.plotly_chart(fig_ts, use_container_width=True)

with tab_heatmap:
    st.markdown("#### Weekly Congestion Matrix (00:00 — 23:00)")
    st.caption(
        "Values inside cells show the average traffic congestion percentage for that hour."
    )
    fig_heat = plot_heatmap(compute_heatmap_matrix(df))
    st.plotly_chart(fig_heat, use_container_width=True)

with tab_weather:
    col_w1, col_w2 = st.columns([5, 5])
    with col_w1:
        st.markdown("#### 🌧️ Precipitation Impact on Traffic")
        st.plotly_chart(
            plot_weather_impact(compute_weather_impact(df)),
            use_container_width=True,
        )

    with col_w2:
        st.markdown("#### 🚨 Top 5 Peak Congestion Hours Ahead")
        top_peaks = (
            df.sort("predicted_traffic_index_av", descending=True)
            .head(5)
            .select(
                [
                    pl.col("timestamp").alias("Timestamp"),
                    pl.col("predicted_traffic_index_av").alias("Traffic Index (%)"),
                    pl.col("precipitation").alias("Precipitation (mm)"),
                    pl.col("temperature_2m").alias("Temperature (°C)"),
                ]
            )
            .to_pandas()
        )
        st.dataframe(top_peaks, use_container_width=True, hide_index=True)

with tab_data:
    st.markdown("#### Forecast Dataset Details")
    cols = [
        "timestamp",
        "predicted_traffic_index_av",
        "temperature_2m",
        "precipitation",
        "wind_speed_10m",
        "is_weekend",
        "is_holiday",
    ]
    table_df = filtered_df.select(cols).to_pandas()
    st.dataframe(table_df, use_container_width=True)

    csv_data = table_df.to_csv(index=False).encode("utf-8")
    st.download_button(
        "📥 Download Filtered Data as CSV",
        csv_data,
        f"istanbul_traffic_forecast_{datetime.now().strftime('%Y%m%d')}.csv",
        "text/csv",
    )
